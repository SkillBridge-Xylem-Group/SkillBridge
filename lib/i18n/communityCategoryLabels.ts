const TABLES: Record<AppLocale, CategoryLabelTable> = {
  en,
  "zh-CN": zhCN,
  id,
  ja,
  ko,
};

/** Translate a system community category / topic for display. Unknown custom labels stay as-is. */
export function categoryLabel(locale: AppLocale, category: string): string {
  return TABLES[locale]?.[category] ?? category;
}

/** Ensure every catalog topic has an English baseline entry (dev guard). */
export function assertCategoryCoverage(): void {
  for (const topic of COMMUNITY_TOPICS) {
    if (!en[topic]) console.warn(`[i18n] missing category label: ${topic}`);
  }
}
